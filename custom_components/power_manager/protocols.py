"""Safety-checked optional outbound transports for Power Manager.

Every device command is generated by the independent kW->code profile before
it gets here. There are no implicit register conventions or PV-specific codes.
The Modbus path sends FC16 or FC06 without extra Python packages, validates
the response and closes the connection after each transaction.
"""
from __future__ import annotations

import asyncio
import ipaddress
import struct
from math import isfinite
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from homeassistant.core import HomeAssistant


class TransportError(RuntimeError):
    """No confirmed command transmission was possible."""


def encode_modbus_registers(value: float, data_type: str, byte_order: str) -> tuple[int, ...]:
    """Encode one finite device code as 16-bit Modbus registers."""
    if not isfinite(value):
        raise TransportError("Modbus value is not finite")
    formats = {"float32": "f", "uint16": "H", "int16": "h",
               "uint32": "I", "int32": "i"}
    if data_type not in formats:
        raise TransportError("Unsupported Modbus data type")
    if byte_order not in {"ABCD", "BADC", "CDAB", "DCBA"}:
        raise TransportError("Unsupported Modbus byte order")
    if data_type != "float32" and not value.is_integer():
        raise TransportError("Integer Modbus code cannot represent a fractional value")
    try:
        wire = struct.pack(">" + formats[data_type], value if data_type == "float32" else int(value))
    except (OverflowError, ValueError, struct.error) as exc:
        raise TransportError("Modbus value outside data type range") from exc
    if len(wire) == 4:
        positions = {"ABCD": (0,1,2,3), "BADC": (1,0,3,2),
                     "CDAB": (2,3,0,1), "DCBA": (3,2,1,0)}
        wire = bytes(wire[i] for i in positions[byte_order])
    return tuple(struct.unpack(">H", wire[i:i+2])[0] for i in range(0, len(wire), 2))


def build_modbus_request(*, transaction: int, unit_id: int, address: int,
                         values: tuple[int, ...], function: int = 16) -> bytes:
    """Build MBAP/PDU, disallow any unintended coil/read or broadcast write."""
    if not 0 <= transaction <= 65535 or not 1 <= unit_id <= 247:
        raise TransportError("Invalid Modbus transaction or unit ID")
    if not 0 <= address <= 65535 or not values or len(values) > 123:
        raise TransportError("Invalid Modbus register address or count")
    if address + len(values) > 65536:
        raise TransportError("Modbus register address overflow")
    if any(not 0 <= v <= 65535 for v in values):
        raise TransportError("Modbus register outside UInt16")
    if function == 6:
        if len(values) != 1:
            raise TransportError("FC06 only supports a single register")
        pdu = struct.pack(">BHH", 6, address, values[0])
    elif function == 16:
        pdu = struct.pack(">BHHB", 16, address, len(values), 2 * len(values))
        pdu += struct.pack(">" + "H" * len(values), *values)
    else:
        raise TransportError("Only holding-register FC06/FC16 writing is supported")
    return struct.pack(">HHHB", transaction, 0, len(pdu)+1, unit_id) + pdu


def validate_modbus_response(request: bytes, response: bytes) -> None:
    """Require exact transaction, unit, FC, address and register confirmation."""
    if len(response) < 8:
        raise TransportError("Short Modbus response")
    tid, proto, length, unit = struct.unpack(">HHHB", response[:7])
    expected_tid, _, _, expected_unit = struct.unpack(">HHHB", request[:7])
    if (tid,proto,unit)!=(expected_tid,0,expected_unit) or length != len(response)-6:
        raise TransportError("Unexpected Modbus transaction, unit or length")
    fc = request[7]
    if response[7] == (fc | 0x80):
        code = response[8] if len(response) == 9 else None
        raise TransportError(f"Modbus exception response: {code}")
    if response[7] != fc or len(response) != 12:
        raise TransportError("Unexpected Modbus write response")
    if fc == 6:
        if response[8:12] != request[8:12]:
            raise TransportError("FC06 value acknowledgement mismatch")
    elif response[8:12] != request[8:12]:
        raise TransportError("FC16 register count/address mismatch")


async def async_modbus_write(
    *, host: str, port: int, unit_id: int, address: int, value: float,
    data_type: str, byte_order: str, function: int, timeout_s: float,
) -> None:
    """Execute one Modbus TCP write with deadline, strict ACK and no retries."""
    if not host or any(x in host for x in ("\x00", "/", " ", "\n")):
        raise TransportError("Invalid Modbus host")
    if not 1 <= port <= 65535 or not 0 < timeout_s <= 60:
        raise TransportError("Invalid Modbus port or timeout")
    words = encode_modbus_registers(value, data_type, byte_order)
    request = build_modbus_request(
        transaction=1, unit_id=unit_id, address=address,
        values=words, function=function,
    )
    writer = None
    try:
        async with asyncio.timeout(timeout_s):
            reader, writer = await asyncio.open_connection(host, port)
            writer.write(request)
            await writer.drain()
            header = await reader.readexactly(7)
            length = struct.unpack(">H", header[4:6])[0]
            if not 2 <= length <= 253:
                raise TransportError("Invalid Modbus response payload length")
            body = await reader.readexactly(length-1)
            validate_modbus_response(request, header + body)
    except (TimeoutError, OSError, asyncio.IncompleteReadError) as exc:
        raise TransportError(f"Modbus TCP write failed: {exc}") from exc
    finally:
        if writer is not None:
            writer.close()
            try:
                await writer.wait_closed()
            except OSError:
                pass


async def async_mqtt_publish(
    hass: HomeAssistant, *, topic: str, value: float,
    template: str, qos: int, retain: bool,
) -> None:
    """Publish a profile code via the configured Home Assistant MQTT broker."""
    if (
        not topic or topic.startswith(("+", "$SYS/"))
        or any(s in topic for s in ("#", "+", "\x00"))
        or not 0 <= qos <= 2 or "{value}" not in template
        or not isfinite(value)
    ):
        raise TransportError("Invalid MQTT device command configuration")
    if not hass.services.has_service("mqtt", "publish"):
        raise TransportError("HA MQTT publish service is unavailable")
    payload = template.replace("{value}", format(value, ".9g"))
    try:
        await hass.services.async_call(
            "mqtt", "publish",
            {"topic": topic, "payload": payload, "qos": qos, "retain": retain},
            blocking=True,
        )
    except Exception as exc:
        raise TransportError(f"MQTT publish failed: {exc}") from exc
